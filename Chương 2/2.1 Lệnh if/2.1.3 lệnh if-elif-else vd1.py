# Tra cuu ma dan toc trong Python

code = int(input("Nhap ma dan toc (1-5): "))

if code == 1:
    print("Dan toc Kinh")
elif code == 2:
    print("Dan toc Tay")
elif code == 3:
    print("Dan toc Nung")
elif code == 4:
    print("Dan toc Thai")
elif code == 5:
    print("Dan toc Khmer")
else:
    print("Ma khong hop le")
